import Model from "@/foundation/Model";

export default class Invoice extends Model{
    static resource = 'invoice';

	static async invoices(payload) {
		return await this.axios().get(`/?page=${payload.page}`, {params: payload})
	}

    static async getAutoGeneratedInvoiceNumber() {
        return await this.axios().get('/generated-invoice-number')
    }

	static async saveDraft(data, action = 'save_draft') {
		data = {...data, action}
		return await this.axios().post('/', data)
	}

	static async update(invoiceId, data, action) {
		data = {...data, action}
		return await this.axios().put(`/${invoiceId}`, data)
	}

	static async find(id) {
		return await this.axios().get(`/${id}`)
	}

	// static async preview(invoiceId) {
	// 	return await this.axios().get(`/${invoiceId}/preview-pdf`)
	// }

	static async preview(invoiceId) {
		return await this.axios().get(`/${invoiceId}/preview/settings`)
	}

	static async generate(invoiceId) {
		return await this.axios().post(`/${invoiceId}/pdf`)
	}

	static async download(invoiceId) {
		return await this.axios().get(`/${invoiceId}/pdf/download`, {
			responseType: "blob",
		})
	}

	static async sendCopyToBusinessProfile(invoiceId, hasCsvReport = false) {
		return await this.axios().post(`/${invoiceId}/pdf/send-copy-to-business-profile`, {
			hasCsvReport
		})
	}

	static async directlySendToClient(invoiceId, message) {
		return await this.axios().post(`/${invoiceId}/pdf/send-to-client`, {
			message
		})
	}

	static async getInvoicePublicUrl(invoiceId) {
		return await this.axios().get(`/${invoiceId}/preview/public-invoice-link`)
	}

	static async revokeInvoicePublicUrl(invoiceId) {
		return await this.axios().post(`/${invoiceId}/preview/public-invoice-link/revoke`)
	}

	static async renewInvoicePublicUrl(invoiceId) {
		return await this.axios().post(`/${invoiceId}/preview/public-invoice-link/renew`)
	}
}