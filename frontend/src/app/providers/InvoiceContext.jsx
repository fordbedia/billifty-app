"use client";

import React, {
    createContext, Dispatch,
    ReactNode, SetStateAction,
    useContext,
    useState,
    useEffect
} from 'react'
import { useQuery, useQueryClient, useMutation } from '@tanstack/react-query';
import BusinessProfile from "@/app/models/BusinessProfile";
import Clients from "@/app/models/Clients";
import Invoices from "@/app/models/Invoices";
import { today, getLocalTimeZone } from "@internationalized/date";
import {computeInvoice} from "@/app/utils/computeInvoice";

const InvoiceContext = createContext(null)

export function InvoiceProvider({ children }) {

    const tz = getLocalTimeZone();
    const issueDate = today(tz);
    const dueDate = issueDate.add({ months: 1 });

    const invoiceItemsInitialState = {
        position: 1,
        name: '',
        description: '',
        quantity: 1,
        unit: 1,
        unit_price_cents: 0,
        line_discount_cents: 0,
        line_discount_rate: 0,
        tax_rate: 0,
        tax_cents: 0,
        line_total_cents: 0,
        meta: ''
    }

    const [data, setData] = useState({
        business_profile_id: null,
        client_id: null,
        invoice_template_id: null,
        color_scheme_id: null,
        payment_information_id: null,
        invoice_number: '',
        reference: '',
        currency: '',
        issued_on: issueDate,
        due_on: dueDate,
        paid_at: '',
        status: '',
        template_slug: '',
        template_version: '',
        theme_json: '',
        subtotal_cents: 0,
        discount_cents: 0,
        discount_rate: 0,
        tax_cents: 0,
        shipping_cents: 0,
        total_cents: 0,
        amount_due_cents: 0,
        notes: '',
        terms: '',
        pdf_url: '',
        render_snapshot_html: '',
        meta: '',
        invoice_items: []
    })

    const shallowEqualNumbers = (a, b, keys) => {
      return keys.every(k => (a?.[k] ?? null) === (b?.[k] ?? null));
    }


    const {
        data: businessProfileData
    } = useQuery({
        queryKey: ['business-profiles'],
        queryFn: async () => {
            const a = await BusinessProfile.all()
            if (a.data) {
                return a.data
            }
            return null
        }
    })

    const {data: clientData} = useQuery({
        queryKey: ['client'],
        queryFn: async () => {
            const c = await Clients.all()
            if (c.data) {
                return c.data
            }
            return null
        }
    })

    const {data: generatedInvoiceNum} = useQuery({
        queryKey: ['auto-invoice-number'],
        queryFn: async () => (await Invoices.getAutoGeneratedInvoiceNumber())?.data
    })

    useEffect(() => {
        if (!generatedInvoiceNum) return;
        setData((prevState) => ({
            ...prevState,
            invoice_number: generatedInvoiceNum,
        }));
    }, [generatedInvoiceNum])

    const onDataChange = (attr, val) => setData(prev => ({...prev, [attr]: val}))
    const onInvoiceItemChange = (attr, val) => setData(prev => ({
        ...prev,
        invoice_items: [...prev.invoice_items, ]
    }))

    const addItems = () => setData((prev) => ({...prev, invoice_items: [...prev.invoice_items, invoiceItemsInitialState]}))

    const updateItems = (index, field, value) => setData((prev) => {
        const updated = [...prev.invoice_items]
        updated[index] = {...updated[index], [field]: value}
        return {...prev, invoice_items: updated}
    })

    useEffect(() => {
      setData(prev => {
        const next = computeInvoice(prev);

        // Prevent unnecessary state updates (and feedback loops)
        const stableKeys = [
          "subtotal_cents", "tax_cents", "total_cents", "amount_due_cents"
        ];
        const sameTotals = shallowEqualNumbers(prev, next, stableKeys);

        // Compare items' line totals too
        const sameItems =
          prev.invoice_items?.length === next.invoice_items?.length &&
          prev.invoice_items.every((it, i) =>
            (it.line_total_cents ?? 0) === (next.invoice_items[i].line_total_cents ?? 0)
          );

        if (sameTotals && sameItems) return prev;
        return next;
      });
    }, [
      // When these change, recompute:
      data.invoice_items,          // items array (reference changes on edits/adds)
      data.discount_cents,
      data.tax_cents,
      data.tax_rate_bps,           // optional, if you support it
      data.shipping_cents,
    ]);

    const value = {
        businessProfileData,
        clientData,
        generatedInvoiceNum,
        data,
        onDataChange,
        addItems,
        updateItems
    }

    return <InvoiceContext.Provider value={value}>
        {children}
    </InvoiceContext.Provider>
}

export const useInvoice = () => {
  const ctx = useContext(InvoiceContext);
  if (!ctx) throw new Error("useInvoice must be used within InvoiceProvider");
  return ctx;
};